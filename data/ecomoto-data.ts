/**
 * Retorna exclusivamente las motos listas para el catálogo público / comparador
 * Excluye explícitamente registros marcados como SOLO_COMPATIBILIDAD (Regla 7)
 */
export function getPublicCatalogMotos(): MotoModel[] {
  return OFFICIAL_MOTOS.filter((m) => m.listingStatus === "CATALOGO");
}

/**
 * Obtiene una moto por slug con sus repuestos compatibles verificados / condicionales
 * Reglas 4, 5 y 6: Solo muestra repuestos con compatibilidad confirmada o condicional
 */
export function getMotoWithCompatibleParts(slug: string): MotoDetailWithParts | null {
  const moto = OFFICIAL_MOTOS.find((m) => m.slug === slug);
  if (!moto) return null;

  // Filtrar compatibilidades para esta moto
  const matchingComps = OFFICIAL_COMPATIBILITIES.filter(
    (c) => c.brand.toUpperCase() === moto.brand.toUpperCase() && c.model.toLowerCase() === moto.model.toLowerCase()
  );

  const compatibleParts: CompatiblePartView[] = [];

  for (const comp of matchingComps) {
    // Regla 6: PENDIENTE_DE_COMPATIBILIDAD o REVISAR_FUENTE no se muestran como compatibles
    if (comp.compatibilityStatus !== "CONFIRMADA_EN_FUENTE" && comp.compatibilityStatus !== "CONDICIONAL_FUENTE") {
      continue;
    }

    const part = OFFICIAL_PARTS.find((p) => p.partKey === comp.partKey);
    if (!part) continue;

    compatibleParts.push({
      part,
      compatibilityStatus: comp.compatibilityStatus,
      evidenceNote: comp.evidenceNote,
      sourceUrl: comp.sourceUrl || part.sourceUrl,
      sourceCheckedOn: comp.sourceCheckedOn || part.sourceCheckedOn,
      requiresVariantConfirmation: comp.compatibilityStatus === "CONDICIONAL_FUENTE",
    });
  }

  return {
    ...moto,
    compatibleParts,
  };
}

/**
 * Obtiene un repuesto por partKey con la lista de motos compatibles publicadas
 */
export function getPartWithCompatibleMotos(partKey: string) {
  const part = OFFICIAL_PARTS.find((p) => p.partKey === partKey);
  if (!part) return null;

  const comps = OFFICIAL_COMPATIBILITIES.filter((c) => c.partKey === partKey);
  const compatibleMotos = comps.map((c) => {
    const moto = OFFICIAL_MOTOS.find(
      (m) => m.brand.toUpperCase() === c.brand.toUpperCase() && m.model.toLowerCase() === c.model.toLowerCase()
    );
    return {
      brand: c.brand,
      model: c.model,
      motoSlug: moto?.slug,
      isFullCatalogModel: moto?.listingStatus === "CATALOGO",
      compatibilityStatus: c.compatibilityStatus,
      evidenceNote: c.evidenceNote,
      sourceUrl: c.sourceUrl,
    };
  });

  return {
    part,
    compatibleMotos,
  };
}
