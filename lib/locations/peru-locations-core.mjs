/**
 * Obtener lista ordenada de departamentos
 */
export function getDepartmentNames() {
  return PERU_DEPARTMENTS.map((d) => d.name).sort((a, b) => a.localeCompare(b));
}

/**
 * Obtener lista de provincias para un departamento dado
 */
export function getProvincesForDepartment(deptName) {
  if (!deptName) return [];
  const dept = PERU_DEPARTMENTS.find(
    (d) => d.name.toLowerCase() === deptName.trim().toLowerCase()
  );
  if (!dept) return [];
  return dept.provinces.map((p) => p.name);
}

/**
 * Obtener lista de distritos para un departamento y provincia dados
 */
export function getDistrictsForProvince(deptName, provName) {
  if (!deptName) return [];
  const dept = PERU_DEPARTMENTS.find(
    (d) => d.name.toLowerCase() === deptName.trim().toLowerCase()
  );
  if (!dept) return [];

  if (provName) {
    const prov = dept.provinces.find(
      (p) => p.name.toLowerCase() === provName.trim().toLowerCase()
    );
    if (prov) return prov.districts;
  }

  // Si no se especifica provincia, devolver todos los distritos del departamento
  const allDistricts = dept.provinces.flatMap((p) => p.districts);
  return Array.from(new Set(allDistricts)).sort((a, b) => a.localeCompare(b));
}
