-- ==============================================================================
-- Migración: Catálogo Inicial MOTOSERVICE
-- Archivo: supabase/migrations/20261009140000_catalogo_inicial.sql
-- Descripción: Creación de tablas base del catálogo de repuestos de motos
--              eléctricas (marcas, modelos_moto, categorias, repuestos y
--              compatibilidades) con restricciones, índices, RLS y políticas
--              de solo lectura para catálogo público.
-- ==============================================================================

BEGIN;

-- ==============================================================================
-- 1. TABLA: marcas
-- ==============================================================================
CREATE TABLE marcas (
    id_marca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_marcas_nombre UNIQUE (nombre)
);

COMMENT ON TABLE marcas IS 'Marcas fabricantes de motos eléctricas.';
COMMENT ON COLUMN marcas.id_marca IS 'Identificador único de la marca.';
COMMENT ON COLUMN marcas.nombre IS 'Nombre comercial de la marca (único).';
COMMENT ON COLUMN marcas.estado IS 'Indica si la marca está activa en la plataforma.';
COMMENT ON COLUMN marcas.created_at IS 'Fecha y hora de registro.';

-- ==============================================================================
-- 2. TABLA: modelos_moto
-- ==============================================================================
CREATE TABLE modelos_moto (
    id_modelo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_marca BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    anio SMALLINT,
    voltaje_nominal_v NUMERIC(6, 2),
    potencia_motor_w INTEGER,
    estado BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_modelos_moto_marca FOREIGN KEY (id_marca)
        REFERENCES marcas (id_marca) ON DELETE RESTRICT,
    CONSTRAINT chk_modelos_moto_voltaje CHECK (voltaje_nominal_v IS NULL OR voltaje_nominal_v >= 0),
    CONSTRAINT chk_modelos_moto_potencia CHECK (potencia_motor_w IS NULL OR potencia_motor_w >= 0)
);

COMMENT ON TABLE modelos_moto IS 'Modelos de motos eléctricas asociadas a una marca.';
COMMENT ON COLUMN modelos_moto.id_modelo IS 'Identificador único del modelo.';
COMMENT ON COLUMN modelos_moto.id_marca IS 'Referencia foránea a la marca fabricante.';
COMMENT ON COLUMN modelos_moto.nombre IS 'Nombre o referencia del modelo.';
COMMENT ON COLUMN modelos_moto.anio IS 'Año del modelo comercial.';
COMMENT ON COLUMN modelos_moto.voltaje_nominal_v IS 'Voltaje nominal del sistema eléctrico en voltios (no negativo).';
COMMENT ON COLUMN modelos_moto.potencia_motor_w IS 'Potencia nominal del motor en vatios (no negativo).';
COMMENT ON COLUMN modelos_moto.estado IS 'Indica si el modelo se encuentra activo.';
COMMENT ON COLUMN modelos_moto.created_at IS 'Fecha y hora de registro.';

-- ==============================================================================
-- 3. TABLA: categorias
-- ==============================================================================
CREATE TABLE categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    estado BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);

COMMENT ON TABLE categorias IS 'Categorías de repuestos y componentes eléctricos.';
COMMENT ON COLUMN categorias.id_categoria IS 'Identificador único de la categoría.';
COMMENT ON COLUMN categorias.nombre IS 'Nombre de la categoría (único).';
COMMENT ON COLUMN categorias.descripcion IS 'Descripción detallada de la categoría.';
COMMENT ON COLUMN categorias.estado IS 'Indica si la categoría está activa en la tienda.';
COMMENT ON COLUMN categorias.created_at IS 'Fecha y hora de registro.';

-- ==============================================================================
-- 4. TABLA: repuestos
-- ==============================================================================
CREATE TABLE repuestos (
    id_repuesto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL,
    codigo_sku VARCHAR(50) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(12, 2) NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'PEN',
    imagen_url TEXT,
    estado BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_repuestos_categoria FOREIGN KEY (id_categoria)
        REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
    CONSTRAINT uq_repuestos_sku UNIQUE (codigo_sku),
    CONSTRAINT chk_repuestos_precio CHECK (precio >= 0)
);

COMMENT ON TABLE repuestos IS 'Catálogo de repuestos para motos eléctricas.';
COMMENT ON COLUMN repuestos.id_repuesto IS 'Identificador único del repuesto.';
COMMENT ON COLUMN repuestos.id_categoria IS 'Referencia foránea a la categoría del repuesto.';
COMMENT ON COLUMN repuestos.codigo_sku IS 'Código SKU único de inventario del repuesto.';
COMMENT ON COLUMN repuestos.nombre IS 'Nombre comercial del repuesto.';
COMMENT ON COLUMN repuestos.descripcion IS 'Ficha técnica o descripción del repuesto.';
COMMENT ON COLUMN repuestos.precio IS 'Precio unitario de venta (no negativo).';
COMMENT ON COLUMN repuestos.moneda IS 'Código ISO de la moneda (por defecto PEN).';
COMMENT ON COLUMN repuestos.imagen_url IS 'URL o ruta de almacenamiento de la imagen del producto.';
COMMENT ON COLUMN repuestos.estado IS 'Indica si el repuesto está activo en el catálogo.';
COMMENT ON COLUMN repuestos.created_at IS 'Fecha y hora de registro.';

-- ==============================================================================
-- 5. TABLA: compatibilidades
-- ==============================================================================
CREATE TABLE compatibilidades (
    id_compatibilidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_repuesto BIGINT NOT NULL,
    id_modelo BIGINT NOT NULL,
    nivel_verificacion VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    observaciones TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_compatibilidades_repuesto FOREIGN KEY (id_repuesto)
        REFERENCES repuestos (id_repuesto) ON DELETE CASCADE,
    CONSTRAINT fk_compatibilidades_modelo FOREIGN KEY (id_modelo)
        REFERENCES modelos_moto (id_modelo) ON DELETE CASCADE,
    CONSTRAINT uq_compatibilidades_repuesto_modelo UNIQUE (id_repuesto, id_modelo),
    CONSTRAINT chk_compatibilidades_nivel_verificacion CHECK (
        nivel_verificacion IN ('PENDIENTE', 'CONFIRMADA', 'NO_COMPATIBLE')
    )
);

COMMENT ON TABLE compatibilidades IS 'Matriz de compatibilidad entre repuestos y modelos de motos eléctricas.';
COMMENT ON COLUMN compatibilidades.id_compatibilidad IS 'Identificador único del registro de compatibilidad.';
COMMENT ON COLUMN compatibilidades.id_repuesto IS 'Referencia foránea al repuesto evaluado.';
COMMENT ON COLUMN compatibilidades.id_modelo IS 'Referencia foránea al modelo de moto evaluado.';
COMMENT ON COLUMN compatibilidades.nivel_verificacion IS 'Nivel de validación técnica (PENDIENTE, CONFIRMADA, NO_COMPATIBLE).';
COMMENT ON COLUMN compatibilidades.observaciones IS 'Notas adicionales de compatibilidad técnica.';
COMMENT ON COLUMN compatibilidades.created_at IS 'Fecha y hora de registro.';

-- ==============================================================================
-- 6. ÍNDICES DE OPTIMIZACIÓN
-- ==============================================================================

-- Búsquedas y filtros en marcas
CREATE INDEX idx_marcas_estado ON marcas (estado);

-- Búsquedas y filtros en modelos_moto
CREATE INDEX idx_modelos_moto_id_marca ON modelos_moto (id_marca);
CREATE INDEX idx_modelos_moto_nombre ON modelos_moto (nombre);
CREATE INDEX idx_modelos_moto_estado ON modelos_moto (estado);

-- Búsquedas y filtros en categorias
CREATE INDEX idx_categorias_estado ON categorias (estado);

-- Búsquedas y filtros en repuestos
CREATE INDEX idx_repuestos_id_categoria ON repuestos (id_categoria);
CREATE INDEX idx_repuestos_nombre ON repuestos (nombre);
CREATE INDEX idx_repuestos_estado ON repuestos (estado);

-- Búsquedas y filtros en compatibilidades
CREATE INDEX idx_compatibilidades_id_repuesto ON compatibilidades (id_repuesto);
CREATE INDEX idx_compatibilidades_id_modelo ON compatibilidades (id_modelo);
CREATE INDEX idx_compatibilidades_nivel_verificacion ON compatibilidades (nivel_verificacion);

-- ==============================================================================
-- 7. SEGURIDAD: ROW LEVEL SECURITY (RLS) Y PRIVILEGIOS
-- ==============================================================================

-- Habilitar RLS en las 5 tablas
ALTER TABLE marcas ENABLE ROW LEVEL SECURITY;
ALTER TABLE modelos_moto ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE repuestos ENABLE ROW LEVEL SECURITY;
ALTER TABLE compatibilidades ENABLE ROW LEVEL SECURITY;

-- Revocar todos los permisos a roles públicos/anónimos y autenticados
REVOKE ALL ON TABLE marcas, modelos_moto, categorias, repuestos, compatibilidades FROM anon, authenticated;

-- Conceder exclusivamente permiso SELECT
GRANT SELECT ON TABLE marcas, modelos_moto, categorias, repuestos, compatibilidades TO anon, authenticated;

-- ==============================================================================
-- 8. POLÍTICAS DE LECTURA PÚBLICA (POLICIES)
-- ==============================================================================

-- Lectura pública para marcas activas
CREATE POLICY "Lectura pública marcas activas"
    ON marcas
    FOR SELECT
    TO anon, authenticated
    USING (estado = true);

-- Lectura pública para modelos activos cuya marca también esté activa
CREATE POLICY "Lectura pública modelos activos"
    ON modelos_moto
    FOR SELECT
    TO anon, authenticated
    USING (
        estado = true
        AND EXISTS (
            SELECT 1
            FROM marcas m
            WHERE m.id_marca = modelos_moto.id_marca
              AND m.estado = true
        )
    );

-- Lectura pública para categorías activas
CREATE POLICY "Lectura pública categorías activas"
    ON categorias
    FOR SELECT
    TO anon, authenticated
    USING (estado = true);

-- Lectura pública para repuestos activos cuya categoría también esté activa
CREATE POLICY "Lectura pública repuestos activos"
    ON repuestos
    FOR SELECT
    TO anon, authenticated
    USING (
        estado = true
        AND EXISTS (
            SELECT 1
            FROM categorias c
            WHERE c.id_categoria = repuestos.id_categoria
              AND c.estado = true
        )
    );

-- Lectura pública para compatibilidades:
-- Solo registros verificados (CONFIRMADA o NO_COMPATIBLE) y cuyos repuesto, categoría, modelo y marca relacionados estén activos
CREATE POLICY "Lectura pública compatibilidades verificadas activas"
    ON compatibilidades
    FOR SELECT
    TO anon, authenticated
    USING (
        nivel_verificacion IN ('CONFIRMADA', 'NO_COMPATIBLE')
        AND EXISTS (
            SELECT 1
            FROM repuestos r
            JOIN categorias c ON c.id_categoria = r.id_categoria
            WHERE r.id_repuesto = compatibilidades.id_repuesto
              AND r.estado = true
              AND c.estado = true
        )
        AND EXISTS (
            SELECT 1
            FROM modelos_moto m
            JOIN marcas ma ON ma.id_marca = m.id_marca
            WHERE m.id_modelo = compatibilidades.id_modelo
              AND m.estado = true
              AND ma.estado = true
        )
    );

COMMIT;
