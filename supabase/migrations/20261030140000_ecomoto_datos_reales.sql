-- ==============================================================================
-- Migración: Integración de Datos Reales de EcoMoto Perú
-- Archivo: supabase/migrations/20261030140000_ecomoto_datos_reales.sql
-- Descripción: Migración aditiva y versionada sobre el esquema de catálogo inicial
--              (marcas, modelos_moto, categorias, repuestos, compatibilidades).
--              Incorpora tabla proveedores, soporte para compatibilidad N:M con
--              evidencia, notas y estado de verificación, y columnas técnicas para
--              motos (clase, química, autonomía, velocidad, listing_status)
--              y repuestos (parámetros eléctricos, conectores, stock/precio proveedor).
-- ==============================================================================

BEGIN;

-- 1. TABLA ADITIVA: proveedores (Normalización de proveedores y políticas comerciales)
CREATE TABLE IF NOT EXISTS proveedores (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    sitio_web TEXT,
    contacto_soporte TEXT,
    politica_comercial VARCHAR(50) NOT NULL DEFAULT 'CONSULTA_EXTERNA',
    estado BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_proveedores_nombre UNIQUE (nombre)
);

COMMENT ON TABLE proveedores IS 'Proveedores oficiales de repuestos y motocicletas eléctricas.';

-- 2. AMPLIACIÓN ADITIVA: marcas
ALTER TABLE marcas ADD COLUMN IF NOT EXISTS logo TEXT;
ALTER TABLE marcas ADD COLUMN IF NOT EXISTS sitio_web TEXT;

-- 3. AMPLIACIÓN ADITIVA: modelos_moto
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS slug VARCHAR(150);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS vehicle_type VARCHAR(50) DEFAULT 'MOTO_ELECTRICA';
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS listing_status VARCHAR(50) NOT NULL DEFAULT 'CATALOGO';
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS data_status VARCHAR(50) NOT NULL DEFAULT 'PARCIAL';
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS precio_referencial_pen NUMERIC(12, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS precio_regular_pen NUMERIC(12, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS precio_min_pen NUMERIC(12, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS precio_max_pen NUMERIC(12, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS precio_ecomoto_pen NUMERIC(12, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS potencia_max_w INTEGER;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS bateria_quimica VARCHAR(50);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS bateria_capacidad_ah NUMERIC(6, 2);
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS bateria_extraible VARCHAR(20) DEFAULT 'NO_DECLARADO';
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS velocidad_max_kmh INTEGER;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS autonomia_min_km INTEGER;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS autonomia_max_km INTEGER;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS source_url TEXT;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS source_checked_on DATE;
ALTER TABLE modelos_moto ADD COLUMN IF NOT EXISTS notas TEXT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_modelos_moto_marca_nombre'
    ) THEN
        ALTER TABLE modelos_moto ADD CONSTRAINT uq_modelos_moto_marca_nombre UNIQUE (id_marca, nombre);
    END IF;
END $$;

-- 4. AMPLIACIÓN ADITIVA: repuestos
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS part_key VARCHAR(100);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS id_proveedor BIGINT;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS id_marca BIGINT;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS precio_proveedor_pen NUMERIC(12, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS precio_regular_proveedor_pen NUMERIC(12, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS precio_min_pen NUMERIC(12, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS precio_max_pen NUMERIC(12, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS stock_proveedor VARCHAR(50) DEFAULT 'CONSULTAR_STOCK';
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS stock_propio_ecomoto INTEGER NOT NULL DEFAULT 0;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS voltaje_electrico_v NUMERIC(6, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS capacidad_electrica_ah NUMERIC(6, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS quimica VARCHAR(50);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS voltaje_salida_v NUMERIC(6, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS corriente_salida_a NUMERIC(6, 2);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS conector_o_ajuste TEXT;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS source_url TEXT;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS source_checked_on DATE;
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS data_status VARCHAR(50);
ALTER TABLE repuestos ADD COLUMN IF NOT EXISTS notas TEXT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_repuestos_proveedor'
    ) THEN
        ALTER TABLE repuestos ADD CONSTRAINT fk_repuestos_proveedor
            FOREIGN KEY (id_proveedor) REFERENCES proveedores (id_proveedor) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_repuestos_marca'
    ) THEN
        ALTER TABLE repuestos ADD CONSTRAINT fk_repuestos_marca
            FOREIGN KEY (id_marca) REFERENCES marcas (id_marca) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_repuestos_part_key'
    ) THEN
        ALTER TABLE repuestos ADD CONSTRAINT uq_repuestos_part_key UNIQUE (part_key);
    END IF;
END $$;

-- 5. AMPLIACIÓN ADITIVA: compatibilidades (Relación N:M enriquecida con status, evidencia y auditoría)
ALTER TABLE compatibilidades ADD COLUMN IF NOT EXISTS status VARCHAR(50) NOT NULL DEFAULT 'PENDIENTE_DE_COMPATIBILIDAD';

-- Migrar los estados históricos al nuevo campo sin alterar otros estados.
UPDATE compatibilidades
SET status = CASE
    WHEN nivel_verificacion = 'CONFIRMADA' THEN 'CONFIRMADA'
    WHEN nivel_verificacion = 'NO_COMPATIBLE' THEN 'NO_COMPATIBLE'
    ELSE status
END
WHERE status = 'PENDIENTE_DE_COMPATIBILIDAD'
  AND nivel_verificacion IN ('CONFIRMADA', 'NO_COMPATIBLE');
ALTER TABLE compatibilidades ADD COLUMN IF NOT EXISTS source_url TEXT;
ALTER TABLE compatibilidades ADD COLUMN IF NOT EXISTS evidence_note TEXT;
ALTER TABLE compatibilidades ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ DEFAULT now();
ALTER TABLE compatibilidades ADD COLUMN IF NOT EXISTS verified_by VARCHAR(100) DEFAULT 'Investigación EcoMoto';

-- Mantener la restricción original de nivel_verificacion.
-- La nueva columna status tiene su propia restricción independiente.
ALTER TABLE compatibilidades DROP CONSTRAINT IF EXISTS chk_compatibilidades_status;

ALTER TABLE compatibilidades ADD CONSTRAINT chk_compatibilidades_status CHECK (
    status IN (
        'CONFIRMADA_EN_FUENTE',
        'CONDICIONAL_FUENTE',
        'PENDIENTE_DE_COMPATIBILIDAD',
        'REVISAR_FUENTE',
        'NO_COMPATIBLE',
        'CONFIRMADA',
        'PENDIENTE'
    )
);

-- 6. ÍNDICES ADITIVOS
CREATE INDEX IF NOT EXISTS idx_modelos_moto_listing_status ON modelos_moto (listing_status);
CREATE INDEX IF NOT EXISTS idx_modelos_moto_vehicle_type ON modelos_moto (vehicle_type);
CREATE INDEX IF NOT EXISTS idx_repuestos_part_key ON repuestos (part_key);
CREATE INDEX IF NOT EXISTS idx_repuestos_id_proveedor ON repuestos (id_proveedor);
CREATE INDEX IF NOT EXISTS idx_compatibilidades_status ON compatibilidades (status);

-- 7. SEGURIDAD Y RLS CONDICIONAL
ALTER TABLE proveedores ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON TABLE proveedores FROM anon, authenticated;
        GRANT SELECT ON TABLE proveedores TO anon, authenticated;
    END IF;
END $$;

DROP POLICY IF EXISTS "Lectura pública proveedores activos" ON proveedores;
CREATE POLICY "Lectura pública proveedores activos"
    ON proveedores
    FOR SELECT
    TO anon, authenticated
    USING (estado = true);

-- Lectura pública solo de compatibilidades verificadas y entidades activas.
-- Se conservan los controles de categoría y marca del esquema original.
DROP POLICY IF EXISTS "Lectura pública compatibilidades verificadas activas" ON compatibilidades;
CREATE POLICY "Lectura pública compatibilidades verificadas activas"
    ON compatibilidades
    FOR SELECT
    TO anon, authenticated
    USING (
        status IN (
            'CONFIRMADA_EN_FUENTE',
            'CONDICIONAL_FUENTE',
            'CONFIRMADA',
            'NO_COMPATIBLE'
        )
        AND EXISTS (
            SELECT 1
            FROM repuestos r
            JOIN categorias c ON c.id_categoria = r.id_categoria
            WHERE r.id_repuesto = compatibilidades.id_repuesto
              AND r.estado = true
              AND c.estado = true
        )
        AND EXISTS (
            SELECT 1
            FROM modelos_moto m
            JOIN marcas ma ON ma.id_marca = m.id_marca
            WHERE m.id_modelo = compatibilidades.id_modelo
              AND m.estado = true
              AND ma.estado = true
        )
    );

COMMIT;
